-- Ejecutar UNA SOLA VEZ, con DAG y pruebas pausados, en el esquema compartido.
-- Requiere AIVO_AUTH_CACHE existente. No modifica reservas ni tokens utilizables.
CREATE TABLE AIVO_AUTH_HISTORY
(
    ID_AUTH             VARCHAR2(36 CHAR) NOT NULL,
    ACCOUNT_KEY         VARCHAR2(64 CHAR) NOT NULL,
    MOTIVO              VARCHAR2(32 CHAR) NOT NULL,
    ESTADO              VARCHAR2(24 CHAR) NOT NULL,
    FECHA_SOLICITUD     DATE NOT NULL,
    FECHA_REGISTRO      DATE,
    FECHA_FINALIZACION  DATE,
    FECHA_RENOVACION    DATE,
    FECHA_VENCIMIENTO   DATE,
    TOKEN_FINGERPRINT   VARCHAR2(64 CHAR),
    HTTP_STATUS         NUMBER(3),
    ERROR_CODIGO        VARCHAR2(80 CHAR),
    ERROR_DETALLE       VARCHAR2(2000 CHAR),
    CONSTRAINT PK_AIVO_AUTH_HISTORY PRIMARY KEY (ID_AUTH),
    CONSTRAINT CK_AIVO_AUTH_HSTATUS CHECK
        (ESTADO IN ('INICIADO', 'GENERADO', 'GENERADO_SIN_CACHE', 'ERROR_AUTH', 'MIGRADO'))
);
CREATE INDEX IX_AIVO_AUTH_HCUENTA ON AIVO_AUTH_HISTORY (ACCOUNT_KEY, FECHA_SOLICITUD);
COMMENT ON TABLE AIVO_AUTH_HISTORY IS
    'Una fila por solicitud de autenticacion; no se reemplaza al renovar. Fechas Lima UTC-5. Sin bearer ni credenciales.';
COMMENT ON COLUMN AIVO_AUTH_HISTORY.TOKEN_FINGERPRINT IS
    'SHA-256 del token recibido, permite correlacion sin guardar un bearer reutilizable.';
COMMENT ON COLUMN AIVO_AUTH_HISTORY.ESTADO IS
    'INICIADO: intento reservado, resultado no confirmado. GENERADO_SIN_CACHE: token recibido, fallo al guardar cache.';

-- Conservar solo el ultimo token recuperable. No inventar autenticaciones pasadas.
-- MIGRADO permite separar este antecedente de las solicitudes auditadas en vivo.
INSERT INTO AIVO_AUTH_HISTORY
    (ID_AUTH, ACCOUNT_KEY, MOTIVO, ESTADO, FECHA_SOLICITUD, FECHA_REGISTRO,
     FECHA_FINALIZACION, FECHA_RENOVACION, FECHA_VENCIMIENTO)
SELECT LOWER(RAWTOHEX(SYS_GUID())), ACCOUNT_KEY, 'MIGRACION', 'MIGRADO',
       DATE '1970-01-01' + NVL(LAST_AUTH_AT, GENERATED_AT) / 86400 - 5 / 24,
       DATE '1970-01-01' + GENERATED_AT / 86400 - 5 / 24,
       DATE '1970-01-01' + GENERATED_AT / 86400 - 5 / 24,
       DATE '1970-01-01' + REFRESH_AT / 86400 - 5 / 24,
       DATE '1970-01-01' + EXPIRES_AT / 86400 - 5 / 24
FROM AIVO_AUTH_CACHE
WHERE GENERATED_AT IS NOT NULL AND TOKEN_ENCRYPTED IS NOT NULL;

CREATE TABLE AIVO_WHATSAPP_INVALID_LOG
(
    ID_INVALIDO        VARCHAR2(36 CHAR) NOT NULL,
    ID_EJECUCION       VARCHAR2(36 CHAR) NOT NULL,
    MODO               VARCHAR2(12 CHAR) NOT NULL,
    ID_PRUEBA          VARCHAR2(64 CHAR),
    PLANTILLA          VARCHAR2(40 CHAR) NOT NULL,
    INCIDENCIA         VARCHAR2(128 CHAR),
    NUMERO_CLIENTE     VARCHAR2(64 CHAR),
    NUMERO_DESTINO     VARCHAR2(64 CHAR),
    ESTADO             VARCHAR2(10 CHAR) DEFAULT 'INVALIDO' NOT NULL,
    INTENTOS           NUMBER(1) DEFAULT 0 NOT NULL,
    MOTIVO             VARCHAR2(2000 CHAR) NOT NULL,
    DATOS_ORIGEN_JSON  CLOB NOT NULL,
    FECHA_REGISTRO     DATE NOT NULL,
    CONSTRAINT PK_AIVO_WA_INVALID PRIMARY KEY (ID_INVALIDO),
    CONSTRAINT CK_AIVO_WA_IMODO CHECK (MODO IN ('PRODUCCION', 'PRUEBA')),
    CONSTRAINT CK_AIVO_WA_ISTATE CHECK (ESTADO = 'INVALIDO' AND INTENTOS = 0)
);
CREATE INDEX IX_AIVO_WA_IEJECUCION ON AIVO_WHATSAPP_INVALID_LOG (ID_EJECUCION, PLANTILLA);
COMMENT ON TABLE AIVO_WHATSAPP_INVALID_LOG IS
    'Observaciones de candidatos invalidos por ejecucion. No son reservas ni intentos de envio. Fechas Lima UTC-5.';

